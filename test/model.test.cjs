const beforeFill=M.clone(fill),filled=M.autofill(fill);
assert.equal(filled.assigned,95);assert.equal(filled.remaining,8);assert.equal(filled.reserved,3);
assert.deepEqual(fill,beforeFill);
assert.equal(M.objectForPlayer(filled.state,fill.players[104].id).id,manualBeacon.id);
assert.equal(M.objectForPlayer(filled.state,fill.players[4].id).id,manualSeat.id);
