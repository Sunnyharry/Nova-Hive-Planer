assert.ok(distance(available[0])<distance(fill.objects[0]),'The first autofill seat is nearer the center than the top-left seat.');
for(let i=1;i<available.length;i++)assert.ok(distance(available[i-1])<=distance(available[i]));
assert.equal(M.objectForPlayer(filled.state,fill.players[0].id).id,available[0].id);
